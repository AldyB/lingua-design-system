/**
 * @lingua/docs build script — Phase 4
 *
 * Assembles dist/ in dependency order:
 *   1. Token CSS     ← packages/tokens/dist/css/
 *   2. Brand SVGs    ← packages/icons/dist/
 *   3. tokens-export.js ← window.LDS shim for Babel-in-browser explorer
 *   4. Static docs   ← apps/docs/ (HTML, CSS, JSX, components/)
 *   5. Storybook     ← packages/react/storybook-static/ (if built)
 *
 * Phase 4 CI runs: pnpm tokens:build → pnpm build-storybook → pnpm build
 */

import {
  readdirSync, copyFileSync, mkdirSync, writeFileSync,
  statSync, existsSync, cpSync,
} from 'node:fs';
import { resolve, dirname, extname } from 'node:path';
import { fileURLToPath }            from 'node:url';

const __dirname     = dirname(fileURLToPath(import.meta.url));
const SRC           = resolve(__dirname, '..');
const ROOT          = resolve(SRC, '../..');
const DIST          = resolve(SRC,  'dist');
const TOKENS_DIST   = resolve(ROOT, 'packages/tokens/dist');
const ICONS_DIST    = resolve(ROOT, 'packages/icons/dist');
const STORYBOOK_SRC = resolve(ROOT, 'packages/react/storybook-static');

// ── 0. Ensure output dirs ──────────────────────────────────────────────────
mkdirSync(resolve(DIST, 'components'), { recursive: true });

// ── 1. Token CSS ───────────────────────────────────────────────────────────
const TOKEN_CSS = ['lingua.light.css', 'lingua.dark.css'];
let tokenCount = 0;
for (const f of TOKEN_CSS) {
  const src = resolve(TOKENS_DIST, 'css', f);
  if (existsSync(src)) {
    copyFileSync(src, resolve(DIST, f));
    tokenCount++;
  } else {
    console.warn(`⚠  Token CSS missing: ${src} — run pnpm tokens:build first`);
  }
}

// ── 2. Brand SVGs ──────────────────────────────────────────────────────────
let iconCount = 0;
if (existsSync(ICONS_DIST)) {
  for (const f of readdirSync(ICONS_DIST).filter(f => f.endsWith('.svg'))) {
    copyFileSync(resolve(ICONS_DIST, f), resolve(DIST, f));
    iconCount++;
  }
}

// ── 3. tokens-export.js (window.LDS shim) ─────────────────────────────────
//
// Reads packages/tokens/dist/js/tokens.mjs (ESM) and emits a UMD-style
// script that sets window.LDS so ds-components.jsx can read it without
// needing a bundler.
//
const tokensMjs = resolve(TOKENS_DIST, 'js/tokens.mjs');
if (existsSync(tokensMjs)) {
  // Dynamic import of the ESM module so we get the live resolved values
  const { tokens, cssVars } = await import(tokensMjs);
  const payload = JSON.stringify({ tokens, cssVars }, null, 2);
  writeFileSync(
    resolve(DIST, 'tokens-export.js'),
    `/* Auto-generated by @lingua/docs build — do not edit */\nwindow.LDS = ${payload};\n`,
  );
  console.log('✓  tokens-export.js → window.LDS');
} else {
  // Emit a stub so the page doesn't crash if tokens weren't built
  writeFileSync(
    resolve(DIST, 'tokens-export.js'),
    `window.LDS = null; console.warn('[lingua-ds] tokens-export.js is a stub — run pnpm tokens:build');\n`,
  );
  console.warn('⚠  tokens-export.js stub written (pnpm tokens:build not run)');
}

// ── 4. Static docs files ───────────────────────────────────────────────────
const STATIC_EXTS = new Set(['.html', '.css', '.js', '.jsx', '.svg', '.png', '.ico', '.json']);
let staticCount = 0;

for (const entry of readdirSync(SRC)) {
  if (['dist', 'node_modules', 'scripts', 'components'].includes(entry)) continue;
  const stat = statSync(resolve(SRC, entry));
  if (stat.isFile() && STATIC_EXTS.has(extname(entry))) {
    copyFileSync(resolve(SRC, entry), resolve(DIST, entry));
    staticCount++;
  }
}

// Copy components/ subdirectory (Storybook iframe page)
const compSrc  = resolve(SRC, 'components');
const compDist = resolve(DIST, 'components');
if (existsSync(compSrc)) {
  for (const f of readdirSync(compSrc)) {
    if (STATIC_EXTS.has(extname(f))) {
      copyFileSync(resolve(compSrc, f), resolve(compDist, f));
      staticCount++;
    }
  }
}

// ── 5. Storybook static build ──────────────────────────────────────────────
let storybookCopied = false;
if (existsSync(STORYBOOK_SRC)) {
  const sbDist = resolve(DIST, 'storybook');
  mkdirSync(sbDist, { recursive: true });
  cpSync(STORYBOOK_SRC, sbDist, { recursive: true });
  storybookCopied = true;
  console.log('✓  Storybook build → dist/storybook/');
} else {
  console.log('ℹ  Storybook not built — dist/storybook/ skipped');
  console.log('   Run: pnpm --filter @lingua/react build-storybook');
}

// ── Summary ────────────────────────────────────────────────────────────────
console.log(`✓  @lingua/docs — Phase 4 build complete`);
console.log(`   Token CSS: ${tokenCount} file(s)`);
console.log(`   Icons: ${iconCount} SVG(s)`);
console.log(`   Static: ${staticCount} file(s)`);
console.log(`   Storybook: ${storybookCopied ? 'copied ✓' : 'skipped (not built)'}`);
